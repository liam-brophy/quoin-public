/**
 * @param specs from readIdmlStyles (or null for structure-only CSS)
 * @param used { paragraph: Set<string>, character: Set<string> } style names the book uses
 * @param o { body: name of the body style for the 1em base, fallbacks: font fallbacks }
 */
export function stylesToCss(specs, used, o = {}) {
  // House rule (profile.fonts): families the house never uses map to the body face, as in the InDesign build.
  REPLACE = new Map((o.fonts?.replace ?? []).map((f) => [f, o.fonts.with]))
  if (!specs) return { css: BASE, missing: [] }
  const body = o.body && specs.paragraph.get(o.body)
  const basePt = num(body?.PointSize, 12)
  const rules = []
  const missing = []
  for (const n of used.paragraph) {
    const s = specs.paragraph.get(n)
    if (s) rules.push(paragraphRule(n, s, basePt, o.fallbacks))
    else missing.push(n)
  }
  for (const n of used.character) {
    const s = specs.character.get(n)
    if (s) { const rule = characterRule(n, s, o.fallbacks); if (rule) rules.push(rule) }
  }
  // @namespace must precede other rules; move it to the top.
  const base = BASE.replace(/@namespace[^\n]*\n/, '')
  return { css: `@namespace epub "http://www.idpf.org/2007/ops";\n${base}\n${rules.join('\n\n')}\n`, missing }
}
